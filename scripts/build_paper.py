"""
Fill paper/body.template.tex from results/paper_numbers.json and build both PDFs.
Refuses to build if any {{placeholder}} is unknown or any key is unused-but-required, so no number is typed.

  paper/main_single.tex  -> paper/AIR2027_submission.pdf      (single column, the format the call asks for)
  paper/main_twocol.tex  -> paper/AIR2027_twocolumn_check.pdf  (two columns, to check the 6-page camera-ready limit)
"""
import json
import os
import re
import shutil
import subprocess
import sys

import common as C

PAPER = os.path.join(C.AIR, "paper")
BUILD = os.path.join(PAPER, "build")


def fill_one(template, target, nums, head_note):
    src = open(os.path.join(PAPER, template)).read()
    keys = re.findall(r"\{\{([A-Za-z0-9_]+)\}\}", src)
    missing = sorted({k for k in keys if k not in nums})
    if missing:
        sys.exit(f"REFUSING TO BUILD: {len(missing)} placeholder(s) in {template} without a value: {missing}")
    out = re.sub(r"\{\{([A-Za-z0-9_]+)\}\}", lambda m: nums[m.group(1)]["value"], src)
    if re.search(r"\{\{[A-Za-z0-9_]+\}\}", out):
        sys.exit(f"REFUSING TO BUILD: unresolved placeholders remain in {template}")
    head = f"% GENERATED by scripts/build_paper.py from {template}; edit the template, never this file.\n"
    open(os.path.join(PAPER, target), "w").write(head + out)
    return keys


def fill():
    nums = json.load(open(os.path.join(C.RESULTS, "paper_numbers.json")))
    keys = fill_one("body.template.tex", "body.tex", nums, "")
    akeys = fill_one("appendix.template.tex", "appendix.tex", nums, "")
    used = sorted(set(keys) | set(akeys))
    json.dump({"n_placeholders": len(keys) + len(akeys), "n_distinct_keys": len(used),
               "n_body_keys": len(set(keys)), "n_appendix_keys": len(set(akeys)), "keys": used},
              open(os.path.join(C.RESULTS, "build_keys.json"), "w"), indent=1)
    return used


def copy_inputs():
    os.makedirs(BUILD, exist_ok=True)
    for f in os.listdir(PAPER):
        if f.endswith((".tex", ".bib", ".bst", ".cls")):
            shutil.copy(os.path.join(PAPER, f), BUILD)
    figs = os.path.join(BUILD, "figures")
    os.makedirs(figs, exist_ok=True)
    for f in os.listdir(C.FIGURES):
        if f.endswith(".pdf"):
            shutil.copy(os.path.join(C.FIGURES, f), figs)


def latex(main, copy=True, quick=False):
    if copy:
        copy_inputs()
    stem = main[:-4]
    log = []
    pl = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", main]
    # quick: reuse the .bbl/.aux of an earlier full run of the same file (slack.py probes only)
    for cmd in ((pl, pl) if quick else (pl, ["bibtex", stem], pl, pl)):
        r = subprocess.run(cmd, cwd=BUILD, capture_output=True, text=True)
        log.append(r.stdout[-3000:])
        if r.returncode != 0 and cmd[0] == "pdflatex":
            print(r.stdout[-4000:])
            sys.exit(f"LaTeX failed on {main}")
    text = open(os.path.join(BUILD, stem + ".log"), errors="replace").read()
    warn = {"undefined_refs": len(re.findall(r"Reference `[^']+' on page", text)),
            "undefined_cites": len(re.findall(r"Citation `[^']+' on page", text)),
            "overfull": len(re.findall(r"Overfull \\hbox", text))}
    pages = re.findall(r"Output written on .*?\((\d+) pages", text)
    return int(pages[-1]) if pages else None, warn


SLOT_DEFAULT = 0.30


def slot_definition(h):
    """The Step 2 slot: a framed box, one column wide and h\\textheight tall (reserve build only)."""
    return ("\\newcommand{\\stepslot}{\\par\\medskip\\noindent\\fbox{\\parbox[c][%.2f\\textheight][c]"
            "{\\dimexpr\\columnwidth-2\\fboxsep-2\\fboxrule\\relax}{\\centering\\textbf{Step 2 slot}}}\\par\\medskip}" % h)


def build_reserve(h=SLOT_DEFAULT, quick=False):
    """Two-column build with the Step 2 slot drawn at h*textheight. Needs body.tex (run fill() first).
    Writes paper/build/reserve_check.pdf; never touches the normal outputs. Returns (pages, warnings)."""
    copy_inputs()
    body = open(os.path.join(PAPER, "body.tex")).read()
    if "\\stepslot" not in body:
        i = body.find("\\section{Discussion}")
        if i < 0:
            sys.exit("reserve build: no \\stepslot and no \\section{Discussion} in body.tex")
        body = body[:i] + "\\stepslot\n" + body[i:]
    open(os.path.join(BUILD, "body_reserve.tex"), "w").write(body)
    main = open(os.path.join(PAPER, "main_twocol.tex")).read()
    if "\\providecommand{\\stepslot}{}" not in main:
        sys.exit("reserve build: main_twocol.tex lacks \\providecommand{\\stepslot}{}")
    main = main.replace("\\providecommand{\\stepslot}{}", slot_definition(h)).replace("\\input{body.tex}", "\\input{body_reserve.tex}")
    open(os.path.join(BUILD, "main_reserve.tex"), "w").write(main)
    pages, warn = latex("main_reserve.tex", copy=False, quick=quick)
    shutil.copy(os.path.join(BUILD, "main_reserve.pdf"), os.path.join(BUILD, "reserve_check.pdf"))
    return pages, warn


if __name__ == "__main__":
    used = fill()
    out = {}
    for main, pdf in (("main_single.tex", "AIR2027_submission.pdf"), ("main_twocol.tex", "AIR2027_twocolumn_check.pdf")):
        pages, warn = latex(main)
        shutil.copy(os.path.join(BUILD, main[:-4] + ".pdf"), os.path.join(PAPER, pdf))
        out[pdf] = {"pages": pages, **warn}
    if "--reserve" in sys.argv:
        i = sys.argv.index("--reserve")
        h = float(sys.argv[i + 1]) if i + 1 < len(sys.argv) and not sys.argv[i + 1].startswith("-") else SLOT_DEFAULT
        pages, warn = build_reserve(h)
        out["reserve_check.pdf"] = {"pages": pages, "slot_height": h, **warn}
    out["numbers_used"] = len(used)
    json.dump(out, open(os.path.join(C.RESULTS, "build.json"), "w"), indent=1)
    print(json.dumps(out, indent=1))


def plain_abstract():
    """Title and abstract as plain text for the submission form (from the generated body.tex)."""
    body = open(os.path.join(PAPER, "body.tex")).read()
    title = re.search(r"\\title\{(.*?)\}\n", body, flags=re.S).group(1)
    ab = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", body, flags=re.S).group(1)
    kw = re.search(r"\\begin\{IEEEkeywords\}(.*?)\\end\{IEEEkeywords\}", body, flags=re.S).group(1)
    def clean(t):
        t = t.replace("$-$", "-").replace(r"\%", "%").replace("~", " ").replace(r"\,", " ")
        t = re.sub(r"\$([^$]*)\$", r"\1", t)
        t = re.sub(r"\\[a-zA-Z]+\{([^}]*)\}", r"\1", t)
        return re.sub(r"\s+", " ", t).strip()
    out = f"TITLE\n{clean(title)}\n\nABSTRACT\n{clean(ab)}\n\nKEYWORDS\n{clean(kw)}\n"
    open(os.path.join(PAPER, "ABSTRACT.txt"), "w").write(out)
    return len(clean(ab).split())


if __name__ == "__main__":
    print("abstract words:", plain_abstract())
