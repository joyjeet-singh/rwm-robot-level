"""
Fill paper/body.template.tex from results/paper_numbers.json and build both PDFs.
Refuses to build if any {{placeholder}} is unknown or any key is unused-but-required, so no number is typed.

  paper/main_single.tex  -> paper/AIR2027_submission.pdf      (single column, the format the call asks for)
  paper/main_twocol.tex  -> paper/AIR2027_twocolumn_check.pdf  (two columns, to check the 6-page camera-ready limit)
"""
import json
import os
import re
import shutil
import subprocess
import sys

import common as C

PAPER = os.path.join(C.AIR, "paper")
BUILD = os.path.join(PAPER, "build")


def fill():
    nums = json.load(open(os.path.join(C.RESULTS, "paper_numbers.json")))
    src = open(os.path.join(PAPER, "body.template.tex")).read()
    keys = re.findall(r"\{\{([A-Za-z0-9_]+)\}\}", src)
    missing = sorted({k for k in keys if k not in nums})
    if missing:
        sys.exit(f"REFUSING TO BUILD: {len(missing)} placeholder(s) without a value: {missing}")
    out = re.sub(r"\{\{([A-Za-z0-9_]+)\}\}", lambda m: nums[m.group(1)]["value"], src)
    if re.search(r"\{\{[A-Za-z0-9_]+\}\}", out):
        sys.exit("REFUSING TO BUILD: unresolved placeholders remain")
    head = "% GENERATED by scripts/build_paper.py from body.template.tex; edit the template, never this file.\n"
    open(os.path.join(PAPER, "body.tex"), "w").write(head + out)
    used = sorted(set(keys))
    json.dump({"n_placeholders": len(keys), "n_distinct_keys": len(used), "keys": used},
              open(os.path.join(C.RESULTS, "build_keys.json"), "w"), indent=1)
    return used


def latex(main):
    os.makedirs(BUILD, exist_ok=True)
    for f in os.listdir(PAPER):
        if f.endswith((".tex", ".bib", ".bst", ".cls")):
            shutil.copy(os.path.join(PAPER, f), BUILD)
    figs = os.path.join(BUILD, "figures")
    os.makedirs(figs, exist_ok=True)
    for f in os.listdir(C.FIGURES):
        if f.endswith(".pdf"):
            shutil.copy(os.path.join(C.FIGURES, f), figs)
    stem = main[:-4]
    log = []
    for cmd in (["pdflatex", "-interaction=nonstopmode", "-halt-on-error", main], ["bibtex", stem],
                ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", main],
                ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", main]):
        r = subprocess.run(cmd, cwd=BUILD, capture_output=True, text=True)
        log.append(r.stdout[-3000:])
        if r.returncode != 0 and cmd[0] == "pdflatex":
            print(r.stdout[-4000:])
            sys.exit(f"LaTeX failed on {main}")
    text = open(os.path.join(BUILD, stem + ".log"), errors="replace").read()
    warn = {"undefined_refs": len(re.findall(r"Reference `[^']+' on page", text)),
            "undefined_cites": len(re.findall(r"Citation `[^']+' on page", text)),
            "overfull": len(re.findall(r"Overfull \\hbox", text))}
    pages = re.findall(r"Output written on .*?\((\d+) pages", text)
    return int(pages[-1]) if pages else None, warn


if __name__ == "__main__":
    used = fill()
    out = {}
    for main, pdf in (("main_single.tex", "AIR2027_submission.pdf"), ("main_twocol.tex", "AIR2027_twocolumn_check.pdf")):
        pages, warn = latex(main)
        shutil.copy(os.path.join(BUILD, main[:-4] + ".pdf"), os.path.join(PAPER, pdf))
        out[pdf] = {"pages": pages, **warn}
    out["numbers_used"] = len(used)
    json.dump(out, open(os.path.join(C.RESULTS, "build.json"), "w"), indent=1)
    print(json.dumps(out, indent=1))
